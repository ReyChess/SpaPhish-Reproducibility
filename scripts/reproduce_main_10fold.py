#!/usr/bin/env python3
"""Reproduce the main SpaPhish 10-fold rule files and classifier result.

This script compiles the historical miner and classifier from source, uses the
archived folds/training sets that produced the reported results, regenerates
ReglasDataset1.dat ... ReglasDataset10.dat at sigma=0.04, verifies byte-level
SHA-256 identity against the archived rule files, and reruns the classifier.

DivideEn10 is compiled as a provenance/build check but is intentionally NOT used
to regenerate the canonical folds because the historical implementation seeds
its shuffle with time(NULL). The archived folds are therefore the canonical
reproducibility inputs.
"""
from pathlib import Path
import hashlib, os, re, shutil, subprocess, sys, tempfile

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src'
EXP = ROOT / 'experiments' / 'spaphish_feature_ablation_results' / 'feature_ablation' / 'full'
SIGMA = '0.04'
EXPECTED_AVG = 88.2424

def sha256(p: Path) -> str:
    h=hashlib.sha256()
    with p.open('rb') as f:
        for block in iter(lambda: f.read(1024*1024), b''):
            h.update(block)
    return h.hexdigest()

def run(cmd, cwd=None):
    print('+', ' '.join(map(str,cmd)))
    return subprocess.run(cmd, cwd=cwd, check=True, text=True,
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)

def compiler(name, fallback):
    return os.environ.get(name) or shutil.which(fallback) or fallback

def main():
    required=[SRC/'mfi_ct_spaphish_historical.c', SRC/'dmc_ac_spaphish_historical.cpp',
              SRC/'divide_en_10_historical.c', EXP/'Classes.dat']
    required += [EXP/f'{i}.dat' for i in range(1,11)]
    required += [EXP/f'Dataset{i}.dat' for i in range(1,11)]
    required += [EXP/f'ReglasDataset{i}.dat' for i in range(1,11)]
    missing=[str(p.relative_to(ROOT)) for p in required if not p.exists()]
    if missing:
        print('REPRODUCE: FAIL — missing required files')
        for p in missing: print(' -',p)
        return 2

    with tempfile.TemporaryDirectory(prefix='spaphish_repro_') as td:
        work=Path(td)
        miner=work/('mfi_ct_spaphish.exe' if os.name=='nt' else 'mfi_ct_spaphish')
        classifier=work/('dmc_ac_spaphish.exe' if os.name=='nt' else 'dmc_ac_spaphish')
        divider=work/('divide_en_10.exe' if os.name=='nt' else 'divide_en_10')
        cc=compiler('CC','gcc'); cxx=compiler('CXX','g++')
        run([cc,'-O3','-msse4.2',str(SRC/'mfi_ct_spaphish_historical.c'),'-lm','-o',str(miner)])
        run([cxx,'-O3',str(SRC/'dmc_ac_spaphish_historical.cpp'),'-lm','-o',str(classifier)])
        run([cc,'-O2',str(SRC/'divide_en_10_historical.c'),'-o',str(divider)])

        shutil.copy2(EXP/'Classes.dat', work/'Classes.dat')
        for i in range(1,11):
            shutil.copy2(EXP/f'{i}.dat', work/f'{i}.dat')
            shutil.copy2(EXP/f'Dataset{i}.dat', work/f'Dataset{i}.dat')

        exact=0
        for i in range(1,11):
            out=work/f'ReglasDataset{i}.dat'
            r=run([str(miner),str(work/f'Dataset{i}.dat'),SIGMA,str(out)])
            expected=EXP/f'ReglasDataset{i}.dat'
            got_hash, exp_hash = sha256(out), sha256(expected)
            if got_hash != exp_hash:
                print(f'Fold {i}: MISMATCH')
                print(' expected',exp_hash); print(' got     ',got_hash)
                return 3
            exact += 1
            print(f'Fold {i}: EXACT {got_hash}')

        result=work/'results_reproduced.txt'
        run([str(classifier),result.name], cwd=work)
        text=result.read_text(encoding='utf-8', errors='replace')
        m=re.search(r'Eficiencia promedio del proceso\s*=\s*([0-9.]+)', text)
        if not m:
            print('REPRODUCE: FAIL — average accuracy not found')
            return 4
        avg=float(m.group(1))
        if abs(avg-EXPECTED_AVG)>5e-5:
            print(f'REPRODUCE: FAIL — average accuracy {avg:.4f} != {EXPECTED_AVG:.4f}')
            return 5

        print('\nREPRODUCE: OK')
        print(f'Rules regenerated exactly: {exact}/10 folds')
        print(f'Main 10-fold average accuracy: {avg:.4f}%')
        print('Canonical folds: archived experimental folds (not regenerated by DivideEn10)')
        return 0

if __name__=='__main__':
    raise SystemExit(main())
